CREATE DATABASE IF NOT EXISTS ai_student_performance
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ai_student_performance;

CREATE TABLE IF NOT EXISTS users (
    user_id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role ENUM('admin','faculty','student') NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS students (
    student_id INT AUTO_INCREMENT PRIMARY KEY,
    roll_no VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120),
    mobile VARCHAR(20),
    department VARCHAR(80),
    semester INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS faculty (
    faculty_id INT AUTO_INCREMENT PRIMARY KEY,
    faculty_name VARCHAR(100) NOT NULL,
    email VARCHAR(120),
    mobile VARCHAR(20),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS academic_records (
    record_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    attendance DECIMAL(5,2) NOT NULL,
    internal_marks DECIMAL(5,2) NOT NULL,
    assignment_marks DECIMAL(5,2) NOT NULL,
    practical_marks DECIMAL(5,2) NOT NULL,
    previous_cgpa DECIMAL(4,2) NOT NULL,
    backlog_count INT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_student_record (student_id),
    CONSTRAINT fk_academic_student
      FOREIGN KEY (student_id) REFERENCES students(student_id)
      ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS predictions (
    prediction_id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    predicted_result VARCHAR(20) NOT NULL,
    confidence DECIMAL(6,4),
    algorithm VARCHAR(80) NOT NULL,
    prediction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prediction_student
      FOREIGN KEY (student_id) REFERENCES students(student_id)
      ON DELETE CASCADE
);

CREATE INDEX idx_students_name ON students(name);
CREATE INDEX idx_predictions_student ON predictions(student_id);

-- Demo user rows are intentionally omitted because password hashes
